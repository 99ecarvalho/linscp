#!/usr/bin/env python3
"""
Generate the Open Build Service's Debian/Ubuntu recipe from the Debian
packaging, so the two never drift (RELEASE-PLAN, openSUSE - OBS).

  gen_obs_debian.py [--version X.Y.Z] [--out DIR] [--check]

OBS builds Debian packages from flat files next to the release tarball:
debian.<name> becomes debian/<name>, and the .dsc's DEBTRANSFORM-TAR names
the upstream tarball the build unpacks (OBS's debtransform). From
port/packaging/debian it writes, into port/packaging/obs (or --out):

  debian.control, debian.rules, debian.copyright,
  debian.linscp.lintian-overrides   copied unchanged;
  debian.changelog                  one entry, X.Y.Z-1, for the OBS build
                                    (OBS appends its own release number);
  linscp.dsc                        the source description, its fields read
                                    from debian/control.

The version defaults to project(linscp VERSION ...) in CMakeLists.txt; the
changelog's date is the version's NEWS.md heading (## X.Y.Z - YYYY-MM-DD),
so the output only changes with the inputs. The debhelper compatibility
level is the debhelper-compat build dependency, so no debian.compat.
--check writes nothing and fails if a generated file is out of date.

The other files of debian/ (source/format, watch, upstream/metadata,
tests/) are for Debian and Launchpad source packages; OBS needs none of them.
"""
import argparse, datetime, os, re, sys

ROOT = os.path.abspath(os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', '..'))
DEBIAN = os.path.join(ROOT, 'port', 'packaging', 'debian')
OBS = os.path.join(ROOT, 'port', 'packaging', 'obs')
COPIED = ('control', 'rules', 'copyright', 'linscp.lintian-overrides')
# Fields of the source paragraph a .dsc carries (Debian Policy 5.4).
DSC_FIELDS = ('Maintainer', 'Uploaders', 'Homepage', 'Standards-Version',
              'Vcs-Browser', 'Vcs-Git', 'Build-Depends', 'Build-Depends-Arch',
              'Build-Depends-Indep', 'Build-Conflicts')


def fail(msg):
    sys.exit(f'gen_obs_debian: {msg}')


def read(path):
    with open(path, encoding='utf-8') as f:
        return f.read()


def paragraphs(text):
    """debian/control as [{field: value}], comments dropped, continuation
    lines folded into one line (enough for the fields a .dsc needs)."""
    out, cur, last = [], {}, None
    for line in text.split('\n'):
        if line.startswith('#'):
            continue
        if not line.strip():
            if cur:
                out.append(cur)
            cur, last = {}, None
            continue
        if line[0] in ' \t':
            if last is None:
                fail(f'continuation line without a field: {line!r}')
            cur[last] = (cur[last] + ' ' + line.strip()).strip()
            continue
        name, _, value = line.partition(':')
        last = name.strip()
        cur[last] = value.strip()
    if cur:
        out.append(cur)
    return out


def relations(value):
    """A relationship field on one line, its trailing comma dropped."""
    items = [i.strip() for i in value.split(',') if i.strip()]
    return ', '.join(items)


def project_version():
    m = re.search(r'project\(\s*linscp\s+VERSION\s+([0-9]+\.[0-9]+\.[0-9]+)\b',
                  read(os.path.join(ROOT, 'CMakeLists.txt')))
    if not m:
        fail('no project(linscp VERSION X.Y.Z) in CMakeLists.txt')
    return m.group(1)


def release_date(version):
    """The date of the version's NEWS.md heading, as an RFC 5322 date at noon UTC."""
    m = re.search(r'^## ' + re.escape(version) + r'\s+\S+\s+(\d{4}-\d{2}-\d{2})\s*$',
                  read(os.path.join(ROOT, 'NEWS.md')), re.M)
    day = datetime.date.fromisoformat(m.group(1)) if m else datetime.date.today()
    when = datetime.datetime(day.year, day.month, day.day, 12, 0, tzinfo=datetime.timezone.utc)
    return when.strftime('%a, %d %b %Y %H:%M:%S +0000')


def generate(version):
    control = read(os.path.join(DEBIAN, 'control'))
    paras = paragraphs(control)
    source, binaries = paras[0], paras[1:]
    if 'Source' not in source or not binaries:
        fail('debian/control: no source paragraph or no binary package')
    maintainer = source['Maintainer']
    debian_version = f'{version}-1'

    files = {f'debian.{name}': read(os.path.join(DEBIAN, name)) for name in COPIED}
    files['debian.changelog'] = (
        f'{source["Source"]} ({debian_version}) unstable; urgency=medium\n\n'
        f'  * Release {version}, built by the Open Build Service from the\n'
        f'    release tarball (generated by port/tools/gen_obs_debian.py).\n\n'
        f' -- {maintainer}  {release_date(version)}\n')

    archs = sorted({a for b in binaries for a in b.get('Architecture', 'any').split()})
    dsc = [('Format', read(os.path.join(DEBIAN, 'source', 'format')).strip()),
           ('Source', source['Source']),
           ('Binary', ', '.join(b['Package'] for b in binaries)),
           ('Architecture', ' '.join(archs)),
           ('Version', debian_version)]
    for name in DSC_FIELDS:
        if name in source:
            value = relations(source[name]) if name.startswith('Build-') else source[name]
            dsc.append((name, value))
    dsc.append(('DEBTRANSFORM-TAR', f'{source["Source"]}-{version}.tar.xz'))
    files[f'{source["Source"]}.dsc'] = ''.join(f'{k}: {v}\n' for k, v in dsc)
    return files


def main():
    ap = argparse.ArgumentParser(description="Generate OBS's debian.* files from port/packaging/debian.")
    ap.add_argument('--version', help='X.Y.Z (default: CMakeLists.txt)')
    ap.add_argument('--out', default=OBS, help='output directory (default: port/packaging/obs)')
    ap.add_argument('--check', action='store_true', help='fail if a generated file is out of date')
    a = ap.parse_args()
    version = a.version or project_version()
    if not re.fullmatch(r'[0-9]+\.[0-9]+\.[0-9]+', version):
        fail(f'version {version!r} is not X.Y.Z')

    files = generate(version)
    stale = []
    if not a.check:
        os.makedirs(a.out, exist_ok=True)
    for name, text in sorted(files.items()):
        path = os.path.join(a.out, name)
        current = read(path) if os.path.exists(path) else None
        if current == text:
            continue
        if a.check:
            stale.append(name)
            continue
        with open(path, 'w', encoding='utf-8', newline='\n') as f:
            f.write(text)
        if name == 'debian.rules':
            os.chmod(path, 0o755)
        print(path)
    if stale:
        fail(f'out of date in {a.out}: {", ".join(stale)} (run port/tools/gen_obs_debian.py)')
    return 0


if __name__ == '__main__':
    sys.exit(main())
