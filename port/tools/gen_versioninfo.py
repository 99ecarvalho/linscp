#!/usr/bin/env python3
"""
Generate the VERSIONINFO resource upstream's executable carries.

Core reads its own version from the running module's version resource
(Configuration->Version, through CreateFileInfo and VerQueryValue), and
C++Builder writes that resource from the project's VerInfo_* settings. This
reads the same settings from WinSCP.cbproj, so the version follows the pinned
submodule, and writes them as a .rc for windres.

  gen_versioninfo.py --project WinSCP.cbproj --out version.rc
  gen_versioninfo.py --project WinSCP.cbproj --out version.cpp --cxx

The .cpp form is for POSIX, which has no resources: the same data, as the
linscp_OwnVersionInfo the platform layer serves GetFileVersionInfo from.
"""
import argparse, re, sys


def expand(text, value, platform):
    """MSBuild $(Name) references, from the project's own definitions of Name:
    one whose Condition is '$(Platform)'=='X' applies when X is the platform;
    an unconditional one always. $(Platform) itself is the platform; anything
    undefined is empty, as MSBuild makes it."""
    def lookup(m):
        name = m.group(1)
        if name == 'Platform':
            return platform
        for d in re.finditer(rf'<{name}(?:\s+Condition="([^"]*)")?>([^<]*)</{name}>', text):
            cond = d.group(1)
            if cond is None:
                return expand(text, d.group(2), platform)
            c = re.fullmatch(r"\s*'\$\(Platform\)'\s*==\s*'([^']*)'\s*", cond)
            if c and c.group(1) == platform:
                return expand(text, d.group(2), platform)
        return ''
    return re.sub(r'\$\((\w+)\)', lookup, value)


def verinfo(path, platform):
    text = open(path, encoding='utf-8', errors='replace').read()
    # The base configuration's values: the first occurrence of each.
    def tag(name, default=None):
        m = re.search(rf'<VerInfo_{name}>([^<]*)</VerInfo_{name}>', text)
        if m is None:
            if default is None:
                sys.exit(f'{path}: no VerInfo_{name}')
            return default
        return m.group(1)
    version = [int(tag('MajorVer')), int(tag('MinorVer')), int(tag('Release')),
               int(tag('Build', '0'))]
    locale = int(tag('Locale'))
    keys = []
    for item in tag('Keys').split(';'):
        if item:
            k, _, v = item.partition('=')
            keys.append((k, expand(text, v, platform)))
    return version, locale, keys


def rc_string(s):
    return '"' + s.replace('\\', '\\\\').replace('"', '""') + '\\0"'


def render(version, locale, keys):
    v = ','.join(str(n) for n in version)
    # C++Builder writes the Unicode code page (1200) with the project locale.
    block = f'{locale:04X}04B0'
    lines = [
        '// Generated by port/tools/gen_versioninfo.py from WinSCP.cbproj.',
        '#include <winver.h>',
        '1 VERSIONINFO',
        f'FILEVERSION {v}',
        f'PRODUCTVERSION {v}',
        'FILEFLAGSMASK VS_FFI_FILEFLAGSMASK',
        'FILEFLAGS 0',
        'FILEOS VOS__WINDOWS32',
        'FILETYPE VFT_APP',
        'FILESUBTYPE 0',
        'BEGIN',
        '  BLOCK "StringFileInfo"',
        '  BEGIN',
        f'    BLOCK "{block}"',
        '    BEGIN',
    ]
    for k, val in keys:
        lines.append(f'      VALUE "{k}", {rc_string(val)}')
    lines += [
        '    END',
        '  END',
        '  BLOCK "VarFileInfo"',
        '  BEGIN',
        f'    VALUE "Translation", 0x{locale:04X}, 1200',
        '  END',
        'END',
        '',
    ]
    return '\n'.join(lines)


def cxx_string(s):
    out = 'L"'
    for ch in s:
        if ch in '\\"':
            out += '\\' + ch
        elif 32 <= ord(ch) < 127:
            out += ch
        else:
            out += '\\x%04X""' % ord(ch)
    return out + '"'


def render_cxx(version, locale, keys):
    ms = (version[0] << 16) | version[1]
    ls = (version[2] << 16) | version[3]
    lines = [
        '// Generated by port/tools/gen_versioninfo.py from WinSCP.cbproj.',
        '#include "win32_on_posix.h"',
        '',
        'namespace {',
        'const linscp_VersionString Strings[] = {',
    ]
    for k, v in keys:
        lines.append(f'  {{ {cxx_string(k)}, {cxx_string(v)} }},')
    lines += [
        '};',
        'const linscp_VersionInfoData Data = {',
        f'  {{ VS_FFI_SIGNATURE, 0x00010000, 0x{ms:08X}, 0x{ls:08X}, 0x{ms:08X}, 0x{ls:08X},',
        '    0x3F, 0, 0x00040004, 1, 0, 0, 0 },',
        f'  0x{locale:04X}, 1200, {len(keys)}, Strings',
        '};',
        '}  // namespace',
        '',
        'extern "C" const linscp_VersionInfoData * linscp_OwnVersionInfo(void)',
        '{',
        '  return &Data;',
        '}',
        '',
    ]
    return '\n'.join(lines)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--project', required=True)
    ap.add_argument('--out', required=True)
    ap.add_argument('--cxx', action='store_true')
    # The MSBuild platform, for the project's $(...) properties: Win64 for
    # this port's Windows build, which is x86-64; anything else matches no
    # platform condition.
    ap.add_argument('--platform', default='Win64')
    a = ap.parse_args()
    data = (render_cxx if a.cxx else render)(*verinfo(a.project, a.platform))
    try:
        if open(a.out, encoding='utf-8').read() == data:
            return 0
    except FileNotFoundError:
        pass
    open(a.out, 'w', encoding='utf-8').write(data)
    return 0


if __name__ == '__main__':
    sys.exit(main())
