#!/usr/bin/env python3
"""Windows' locales, as VCL's TLanguages and GetLocaleInfo see them, for the
platforms that have no such data (port/gui/locales.inc, ADR 0014).

WinSCP's GUI matches its translations to locales by Windows' own three-letter
language abbreviations (TGUIConfiguration::GetLocales), so the table is
Windows' data, not a reconstruction:

  On Windows:   windows_locales.py --dump > locales.json
  Anywhere:     windows_locales.py --cxx locales.json > port/gui/locales.inc

Each row: LCID, LOCALE_SABBREVLANGNAME, LOCALE_SNAME, LOCALE_SENGLANGUAGE,
LOCALE_SLANGUAGE (as the UI language shows it: English), and
LOCALE_SNATIVELANGNAME; the locales EnumSystemLocales lists as supported.
"""
import argparse, json, sys


def dump():
    import ctypes
    import ctypes.wintypes as w
    k = ctypes.WinDLL('kernel32', use_last_error=True)
    k.GetLocaleInfoW.argtypes = [w.DWORD, w.DWORD, w.LPWSTR, ctypes.c_int]

    def info(lcid, t):
        b = ctypes.create_unicode_buffer(256)
        return b.value if k.GetLocaleInfoW(lcid, t, b, 256) else ''
    lcids = []
    proc = ctypes.WINFUNCTYPE(w.BOOL, w.LPWSTR)(lambda s: lcids.append(int(s, 16)) or True)
    k.EnumSystemLocalesW(proc, 2)  # LCID_SUPPORTED
    rows = [[l, info(l, 0x3), info(l, 0x5c), info(l, 0x1001), info(l, 0x2), info(l, 0x4)]
            for l in sorted(set(lcids))]
    json.dump(rows, sys.stdout, ensure_ascii=False)


def cxx(path):
    rows = json.load(open(path, encoding='utf-8'))

    def lit(s):
        return 'L"' + s.replace('\\', '\\\\').replace('"', '\\"') + '"'
    print('// Generated by port/tools/windows_locales.py from Windows 11\'s own')
    print('// locale data; do not edit. See port/gui/GuiShim.h.')
    for r in rows:
        print('{ 0x%04X, %s, %s, %s, %s, %s },' % (r[0], lit(r[1]), lit(r[2]), lit(r[3]), lit(r[4]), lit(r[5])))


if __name__ == '__main__':
    ap = argparse.ArgumentParser()
    ap.add_argument('--dump', action='store_true')
    ap.add_argument('--cxx')
    a = ap.parse_args()
    if a.dump:
        dump()
    elif a.cxx:
        cxx(a.cxx)
    else:
        ap.error('--dump or --cxx')
